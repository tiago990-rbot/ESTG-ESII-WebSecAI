import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
import fs from "node:fs/promises";
import { randomBytes } from "node:crypto";
import assert from "node:assert/strict";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "frontend", "package.json"));
const { chromium } = require("playwright");
const out = path.join(root, "test-results");
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: process.env.WEBSECAI_BROWSER || "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const pageErrors = [];
page.on("pageerror", (e) => pageErrors.push(e.message));
const user = "browser_" + randomBytes(5).toString("hex");
const password = randomBytes(18).toString("base64url");
const base = process.env.WEBSECAI_WEB_URL || "http://127.0.0.1:3000";
const results = {};
try {
  await page.goto(base, { waitUntil: "networkidle" });
  await page.getByRole("heading", { name: "Contexto para compreender o risco." }).waitFor();
  await page.screenshot({ path: path.join(out, "home-desktop.png") });
  await page.getByRole("link", { name: "Criar conta", exact: true }).first().click();
  await page.getByLabel("Username", { exact: true }).fill(user);
  await page.getByLabel("Email", { exact: true }).fill(user + "@example.com");
  await page.getByLabel("Palavra-passe", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await page.waitForURL("**/investigations", { timeout: 30000 });
  await page.getByRole("heading", { name: "Investiga com evidências." }).waitFor();
  results.registration_login_and_workspace = true;
  await page.getByRole("button", { name: "Experimentar demonstração", exact: true }).click();
  await page.waitForURL(/\/investigations\/[a-f0-9-]+$/, { timeout: 30000 });
  await page.getByRole("heading", { name: "loja-exemplo.example", exact: true }).waitFor();
  await page.locator(".demoBanner").waitFor();
  await page.getByText("Concluída", { exact: true }).waitFor();
  assert.equal(await page.locator(".evidenceItem").count(), 4);
  const publication = page.locator(".evidenceItem").filter({ has: page.getByRole("heading", { name: "Exemplo didático: incidente reportado", exact: true }) }).locator("dd").first();
  assert.equal(await publication.innerText(), "01/10/2026");
  assert.match(await page.locator(".aiSection").innerText(), /sem chamada a um modelo de IA/);
  await page.screenshot({ path: path.join(out, "demo-desktop.png") });
  await page.locator(".evidenceItem").first().screenshot({ path: path.join(out, "evidence-card.png") });
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar PDF", exact: true }).click();
  const download = await downloadPromise;
  const pdfPath = path.join(out, "demo-report.pdf");
  await download.saveAs(pdfPath);
  assert.equal((await fs.readFile(pdfPath)).subarray(0, 4).toString(), "%PDF");
  results.demo_evidence_and_pdf = true;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(out, "demo-mobile.png") });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  results.mobile_no_horizontal_overflow = true;
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base + "/investigations", { waitUntil: "networkidle" });
  await page.getByLabel("Domínio ou URL público", { exact: true }).fill("example.com");
  await page.getByRole("button", { name: "Iniciar investigação", exact: true }).click();
  await page.waitForURL(/\/investigations\/[a-f0-9-]+$/, { timeout: 30000 });
  await page.getByRole("heading", { name: "example.com", exact: true }).waitFor();
  await page.getByText("Parcial", { exact: true }).waitFor({ timeout: 45000 });
  assert.equal(await page.locator(".demoBanner").count(), 0);
  const kev = page.locator(".runItem").filter({ has: page.getByText("CISA KEV", { exact: true }) });
  assert.match(await kev.innerText(), /Consultada/);
  assert.equal(await page.locator(".evidenceItem").count(), 5);
  await page.screenshot({ path: path.join(out, "live-cisa-desktop.png") });
  results.real_cisa_data_and_missing_access_states = true;
  const beforeIds = await page.locator(".evidenceItem").evaluateAll((nodes) => nodes.map((node) => node.id).sort());
  const investigationId = new URL(page.url()).pathname.split("/").at(-1);
  const mutation = page.waitForResponse((r) => r.url().endsWith("/" + investigationId + "/retry") && r.request().method() === "POST");
  const refreshed = page.waitForResponse(async (r) => r.url().endsWith("/api/v1/investigations/" + investigationId) && r.request().method() === "GET" && (await r.json()).status === "partial");
  await page.getByRole("button", { name: "Repetir Notícias, fóruns e relatórios", exact: true }).click();
  const retryResponse = await mutation;
  assert.equal(retryResponse.status(), 202);
  assert.equal(retryResponse.request().postDataJSON().provider, "osint");
  const updated = await (await refreshed).json();
  assert.equal(updated.runs.find((run) => run.provider === "osint").status, "not_configured");
  await page.getByRole("button", { name: "Repetir Notícias, fóruns e relatórios", exact: true }).waitFor();
  assert.deepEqual(await page.locator(".evidenceItem").evaluateAll((nodes) => nodes.map((node) => node.id).sort()), beforeIds);
  assert.equal(await page.getByRole("button", { name: "Repetir CISA KEV", exact: true }).count(), 0);
  await page.screenshot({ path: path.join(out, "retry-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: path.join(out, "retry-mobile.png") });
  results.selective_retry_preserves_other_sources = true;
  assert.deepEqual(pageErrors, []);
  results.page_errors = 0;
  await fs.writeFile(path.join(out, "browser-results.json"), JSON.stringify({ checked_at: new Date().toISOString(), ...results }, null, 2));
  console.log(JSON.stringify(results));
} finally {
  await context.close();
  await browser.close();
}
